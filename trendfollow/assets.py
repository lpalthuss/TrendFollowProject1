"""Build the single browser asset from readable source fragments, without npm at runtime."""

import argparse
import json
from pathlib import Path
import textwrap


def bundle(web=None):
    web = Path(web) if web else Path(__file__).with_name("web")
    manifest = json.loads((web / "manifest.json").read_text(encoding="utf-8"))
    names = [manifest["filter"], *manifest["browser"]]
    if len(set(names)) != len(names) or any(
        Path(n).name != n or not n.endswith(".js") for n in names
    ):
        raise ValueError("Invalid browser source manifest")
    fragments = {
        n: (web / "src" / n).read_text(encoding="utf-8").replace("\r\n", "\n").rstrip()
        for n in names
    }
    result = "// Generated by python -m trendfollow.assets. Edit web/src/ instead.\n"
    result += fragments[manifest["filter"]] + "\n\n"
    result += 'if (typeof document !== "undefined") {\n'
    for name in manifest["browser"]:
        result += textwrap.indent("// " + name + "\n" + fragments[name], "  ") + "\n\n"
    return result.rstrip() + "\n}\n"


def check(web=None):
    web = Path(web) if web else Path(__file__).with_name("web")
    expected = bundle(web)
    if (
        not (web / "app.js").exists()
        or (web / "app.js").read_text(encoding="utf-8") != expected
    ):
        raise ValueError("UI bundle is stale. Run: python -m trendfollow.assets")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.check:
        check()
        print("UI bundle matches source fragments.")
    else:
        web = Path(__file__).with_name("web")
        temporary = web / "app.js.tmp"
        temporary.write_text(bundle(web), encoding="utf-8", newline="\n")
        temporary.replace(web / "app.js")
        print("Built web/app.js.")


if __name__ == "__main__":
    main()
